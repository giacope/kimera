# frozen_string_literal: true

require "fileutils"
require "kimera/scope/file_set"
require "tmpdir"

# F3/K3-7: vendored and generated code is not the author's, and a generator
# template evaluated in the test process changed the suite's own settings.
RSpec.describe(Kimera::ForeignFile, :aggregate_failures) do
  def tree(files, &)
    Dir.mktmpdir("kimera-foreign") do |root|
      files.each do |path, body|
        FileUtils.mkdir_p(File.dirname(File.join(root, path)))
        File.write(File.join(root, path), body)
      end
      Dir.chdir(root, &)
    end
  end

  def foreign?(path) = described_class.new(path).foreign?

  it "knows vendored copies and generator templates by their place" do
    places = %w[vendor/gem/a.rb lib/x/vendor/b.rb lib/generators/x/templates/init.rb]
    tree((places + %w[lib/generators/x/install_generator.rb lib/vendors.rb]).to_h { |path| [path, ""] }) do
      expect(%w[vendor/gem/a.rb lib/x/vendor/b.rb lib/generators/x/templates/init.rb].map { |p| foreign?(p) })
        .to(all(be(true)))
      expect(%w[lib/generators/x/install_generator.rb lib/vendors.rb].map { |p| foreign?(p) }).to(all(be(false)))
    end
  end

  %w[.rl .y .racc .treetop .rex].each do |grammar|
    it "knows a file a parser generator wrote by its #{grammar} grammar beside it", :aggregate_failures do
      tree("lib/parser.rb" => "", "lib/parser#{grammar}" => "", "lib/lexer.rb" => "") do
        expect(foreign?("lib/parser.rb")).to(be(true))
        expect(foreign?("lib/lexer.rb")).to(be(false))
      end
    end
  end

  it "knows a generated file by a comment in its first ten lines, never by code" do
    stamped = ->(line, at) { "#{"x = 1\n" * at}#{line}\n" }
    files = {
      "a.rb" => stamped.call("# Generated by racc 1.8", 0), "b.rb" => stamped.call("  # DO NOT EDIT", 9),
      "c.rb" => stamped.call("# do not modify by hand", 10), "d.rb" => "PATTERN = /generated by/\n",
      "e.rb" => "# This file is generated, regenerate it\n"
    }
    tree(files) do
      expect(%w[a.rb b.rb c.rb d.rb e.rb missing.rb].map { |p| foreign?(p) })
        .to(eq([true, true, false, false, false, false]))
    end
  end

  it "leaves them out of a glob, but mutates one named explicitly" do
    tree("lib/a.rb" => "", "lib/generators/x/templates/init.rb" => "", "vendor/v.rb" => "") do
      expect(Kimera::FileSet.new(["lib/**/*.rb", "vendor/**/*.rb"]).files).to(eq(["lib/a.rb"]))
      expect(Kimera::FileSet.new(["lib/generators/x/templates/init.rb"]).files).to(eq(["lib/generators/x/templates/init.rb"]))
    end
  end
end
