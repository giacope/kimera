# frozen_string_literal: true

module Kimera
  class ForeignFile
    PLACES = ["vendor/**/*", "**/vendor/**/*", "**/generators/**/templates/**/*"].freeze
    GRAMMARS = %w[.rl .y .racc .treetop .rex].freeze
    MARKER = /\A\s*#.*\b(?:generated by|do not edit|do not modify)\b/i
    HEAD = 10

    def initialize(path)
      @path = path
    end

    def foreign? = placed? || generated? || marked?

    private

    def placed? = PLACES.any? { |place| File.fnmatch?(place, @path, File::FNM_PATHNAME) }

    def generated?
      stem = @path.delete_suffix(".rb")
      GRAMMARS.any? { |extension| File.file?("#{stem}#{extension}") }
    end

    def marked?
      File.foreach(@path, encoding: Encoding::UTF_8).first(HEAD).any? { |line| line.scrub.match?(MARKER) }
    rescue SystemCallError
      false
    end
  end
end
